import numpy as np
import pandas as pd
from preprocessing.ng_loader import df_all_cycles, generate_row_script
from preprocessing.ng_cycles_stats import calculate_cycles
from scipy.stats import qmc, rv_histogram


def inverse_min_max_normalize(data, min_val, max_val):
    """
    Inverse the min-max normalization of the data.

    Parameters:
    ----------
    data (np.ndarray): The normalized data.
    min_val (float): The minimum value used for normalization.
    max_val (float): The maximum value used for normalization.

    Returns:
    -------
    np.ndarray: A numpy array containing the original data.
    """
    return np.array(data) * (max_val - min_val) + min_val


def generate_len_of_cycles(num_samples=1000, time_unit='months',
                           percent_idle=0.13):
    """
    Generate synthetic injection and withdrawal cycles based on the statistics
    of the real cycles.

    Parameters:
    ----------
    num_samples (int): The number of synthetic samples to generate.
    time_unit (str): The unit of time for the duration calculation ('days',
    'weeks' or 'months').

    Returns:
    -------
    pd.DataFrame: A DataFrame containing the synthetic cycles.
    """
    df_all = df_all_cycles('../data/agsi_depleted/', MAXrate=6 *
                           (10**5), time_unit=time_unit, synthetic=True)

    inj_dict, with_dict, idle_dict, site_data = calculate_cycles(df_all)

    inj_cycle_lengths = inj_dict['injection_lengths_normalized']
    with_cycle_lengths = with_dict['withdrawal_lengths_normalized']
    idle_cycle_lengths = idle_dict['idle_lengths_normalized']

    inj_length_hist = rv_histogram(np.histogram(
        inj_cycle_lengths, bins=np.linspace(0, 1, 10)))
    with_length_hist = rv_histogram(np.histogram(
        with_cycle_lengths, bins=np.linspace(0, 1, 10)))
    idle_length_hist = rv_histogram(np.histogram(
        idle_cycle_lengths, bins=5))

    u = qmc.LatinHypercube(d=2, seed=42).random(num_samples)

    idle_samples = int(((num_samples * 2) * percent_idle) / (1 - percent_idle))

    i = qmc.LatinHypercube(d=1, seed=42).random(idle_samples)

    inj_samples = inj_length_hist.ppf(u[:, 0])  # this transforms
    with_samples = with_length_hist.ppf(u[:, 1])
    idle_samples = idle_length_hist.ppf(i[:, 0])

    inj_max = inj_dict['injection_min_max'][1]
    with_max = with_dict['withdrawal_min_max'][1]
    idle_max = idle_dict['idle_min_max'][1]

    inj_min = inj_dict['injection_min_max'][0]
    with_min = with_dict['withdrawal_min_max'][0]
    idle_min = idle_dict['idle_min_max'][0]

    inj_lengths_real = inverse_min_max_normalize(
        inj_samples, inj_min, inj_max).round().astype(int)
    with_lengths_real = inverse_min_max_normalize(
        with_samples, with_min, with_max).round().astype(int)
    idle_lengths_real = inverse_min_max_normalize(
        idle_samples, idle_min, idle_max).round().astype(int)

    print(
        f"""Inj_samples mean: {np.mean(inj_lengths_real)}, std: {np.std(
            inj_lengths_real)}, median: {np.median(inj_lengths_real)}""")
    print(
        f"""With_samples mean: {np.mean(with_lengths_real)}, std: {np.std(
            with_lengths_real)}, median: {np.median(with_lengths_real)}""")
    print(
        f"""Idle_samples mean: {np.mean(idle_lengths_real)}, std: {np.std(
            idle_lengths_real)}, median: {np.median(idle_lengths_real)}""")

    print('Normalized ___________________________')

    print(
        f"""Inj_samples mean: {np.mean(inj_samples)}, std: {np.std(
            inj_samples)}, median: {np.median(inj_samples)}""")
    print(
        f"""With_samples mean: {np.mean(with_samples)}, std: {np.std(
            with_samples)}, median: {np.median(with_samples)}""")
    print(
        f"""Idle_samples mean: {np.mean(idle_samples)}, std: {np.std(
            idle_samples)}, median: {np.median(idle_samples)}""")

    return pd.DataFrame({
        'injection_lengths': inj_samples,
        'withdrawal_lengths': with_samples,
        'injection_lengths_real': inj_lengths_real,
        'withdrawal_lengths_real': with_lengths_real,
    }), pd.DataFrame({
        'idle_lengths': idle_samples,
        'idle_lengths_real': idle_lengths_real
    })


def length_to_individual_months(df, idle_df, num_samples, percent_idle=0.13):
    """
    Splits the total cycle length generated by LHS into individual months for
    each phase (injection, withdrawal, idle) and
    adds a idle phase after injection or withdrawal based on the percent_idle
    parameter.

    Parameters:
    ----------
    df (pd.DataFrame): A DataFrame containing the synthetic cycles.
    idle_df (pd.DataFrame): A DataFrame containing the synthetic idle cycles.
    num_samples (int): The number of synthetic samples generated.
    percent_idle (float): The percentage of idle cycles to be added.

    Returns:
    -------
    pd.DataFrame: A DataFrame containing the synthetic cycles with individual
    months and idle phases added.
    """
    df_indiv = pd.DataFrame()
    count = 0
    site = 1
    idle_idx = 0
    idle_prob = (num_samples * percent_idle) / (1 - percent_idle)
    for idx, row in df.iterrows():
        # if idle should be added after injection or after withdrawal
        # this generates a random number to see if idle cycle shoudl be added
        rand_num1 = np.random.rand()
        rand_num2 = np.random.rand()  # where idle should be added

        # needed as int rounds down whereas round rounds to nearest integer
        inj_l = max(1, int(round(row['injection_lengths_real'])))
        # needed as int rounds down whereas round rounds to nearest integer
        with_l = max(1, int(round(row['withdrawal_lengths_real'])))

        # generates the number of months for the injection and withdrawal
        # phases
        inj_months = np.arange(1, inj_l + 1)
        with_months = np.arange(1, with_l + 1)

        df_inj = pd.DataFrame({
            'Month': inj_months,
            'Cycle_position_normalized': (inj_months / inj_l),
            'Phase': np.full(inj_l, 'injection'),
        })

        df_with = pd.DataFrame({
            'Month': with_months,
            'Cycle_position_normalized': (with_months / with_l),
            'Phase': np.full(with_l, 'withdrawal'),
        })
        if rand_num1 <= idle_prob:  # add idle phase
            if idle_idx >= len(idle_df):
                continue
            row = idle_df.iloc[idle_idx]
            idle_l = max(1, int(round(row['idle_lengths_real'])))
            months = np.arange(1, idle_l + 1)
            df_idle = pd.DataFrame({
                'Month': months,
                'Cycle_position_normalized': (months / idle_l),
                'Phase': np.full(idle_l, 'idle'),
            })
            idle_idx += 1

            count += inj_l + with_l + idle_l
            if rand_num2 < 0.5:  # after injection add idle phase
                df_temp = pd.concat(
                    [df_inj, df_idle, df_with], ignore_index=True)
            else:  # after withdrawal add idle phase
                df_temp = pd.concat(
                    [df_inj, df_with, df_idle], ignore_index=True)
        else:
            df_temp = pd.concat([df_inj, df_with], ignore_index=True)
            count += inj_l + with_l

        df_temp['Site'] = np.full(len(df_temp), site)

        if count >= 120:
            count = 0
            site += 1

        df_indiv = pd.concat([df_indiv, df_temp], ignore_index=True)
    df_indiv['Phase_Change'] = (df_indiv.groupby('Site')['Phase'].transform(
        lambda x: x != x.shift()).astype(int))
    df_indiv['Cycle_ID'] = df_indiv['Phase_Change'].cumsum()
    df_indiv['Normalised_cycle_pos_cut'] = pd.cut(
        df_indiv['Cycle_position_normalized'],
        bins=[0.0, 0.33, 0.66, 1.0],
        labels=[0.33, 0.66, 1.0]
    )  # they are split into 3 bins to add the rate from the injections
    return df_indiv


def get_rate_individual(position, phase, time_unit='months'):
    """
    Get the individual injection or withdrawal rates for a given position and
    phase from the
    Natural Gas data.

    Parameters:
    ----------
    position (float): The position in the cycle (0.33, 0.66, or 1.0).
    phase (str): The phase of the cycle ('injection' or 'withdrawal').
    time_unit (str): The unit of time for the duration calculation ('days',
    'weeks' or 'months').

    Returns:
    -------
    np.ndarray: An array of the individual injection or withdrawal rates for
    the given position and phase"""

    assert phase in [
        'injection', 'withdrawal'], """Phase must be either 'injection' or
    'withdrawal'"""
    assert position in [0.33, 0.66,
                        1.0], "Position must be one of [0.33, 0.66, 1.0]"
    df_all = df_all_cycles('../data/agsi_depleted/', MAXrate=6 *
                           (10**5), time_unit=time_unit, synthetic=True)
    grouped_cycle_months = df_all.groupby(
        ['Normalised_cycle_pos_cut', 'Phase'], observed=True
    )['Normalised_Net_Injection_Withdrawal']
    return grouped_cycle_months.get_group((position, phase)).values


def create_rate_samples(df):
    """
    Create rate samples for injection and withdrawal phases based on the
    normalized cycle position and phase.

    Parameters:
    ----------
    df (pd.DataFrame): A DataFrame containing the synthetic cycles with
    normalised cycle position.

    Returns:
    -------
    dict: A dictionary containing the LHS synthetic rate samples for each
    phase and position.
    """
    vc_inj = df[df['Phase'] ==
                'injection']['Normalised_cycle_pos_cut'].value_counts()
    vc_with = df[df['Phase'] ==
                 'withdrawal']['Normalised_cycle_pos_cut'].value_counts()

    rate_dict = {
        'inj_33': get_rate_individual(0.33, 'injection'),
        'inj_66': get_rate_individual(0.66, 'injection'),
        'inj_100': get_rate_individual(1.0, 'injection'),
        'with_33': get_rate_individual(0.33, 'withdrawal'),
        'with_66': get_rate_individual(0.66, 'withdrawal'),
        'with_100': get_rate_individual(1.0, 'withdrawal')
    }

    LHS_dict = {}
    hist_dict = {}

    for key, values in rate_dict.items():
        position = float(key.split('_')[1])
        pos = position / 100
        phase = key.split('_')[0]
        if phase == 'inj':
            n_samples = vc_inj[pos]
        else:
            n_samples = vc_with[pos]
        LHS_dict[key] = qmc.LatinHypercube(d=1, seed=42).random(
            n_samples)  # uniform distribution of the samples
        hist_dict[key] = rv_histogram(np.histogram(
            values, bins=int(np.sqrt(len(values)))))

    samples_dict = {}
    for key, hist in hist_dict.items():
        # transforms the uniform distribution to the histogram distribution of
        # the rates
        samples_dict[key] = hist.ppf(LHS_dict[key][:, 0])

    return samples_dict


def add_rate_samples(df):
    """
    Add the LHS synthetic rate samples to the synthetic cycles DataFrame based
    on the normalized cycle position and phase.

    Parameters:
    ----------
    df (pd.DataFrame): A DataFrame containing the synthetic cycles with
    normalised cycle position

    Returns:
    -------
    pd.DataFrame: A DataFrame containing the synthetic cycles with LHS
    synthetic rate samples added
    """
    samples_dict = create_rate_samples(df)
    df['Normalised_Net_Injection_Withdrawal'] = 0

    for key, samples in samples_dict.items():
        pos = float(key.split('_')[1])
        position = pos / 100
        phase = key.split('_')[0]
        if phase == 'inj':
            df.loc[(df['Phase'] == 'injection') &
                   (df['Normalised_cycle_pos_cut']
                    == position),
                   'Normalised_Net_Injection_Withdrawal'] = samples
        else:
            df.loc[(df['Phase'] == 'withdrawal') &
                   (df['Normalised_cycle_pos_cut']
                    == position),
                   'Normalised_Net_Injection_Withdrawal'] = samples

    return df


def generate_full_script(n_samples=1000, time_unit='months',
                         percent_idle=0.13):
    """
    Generate a full script of synthetic injection and withdrawal cycles.

    Parameters:
    ----------
    num_samples (int): The number of synthetic samples to generate.
    time_unit (str): The unit of time for the duration calculation ('days',
    'weeks' or 'months').

    Returns:
    -------
    pd.DataFrame: A DataFrame containing the synthetic cycles.
    """
    num_samples = n_samples * 36
    df, idle_df = generate_len_of_cycles(
        num_samples=num_samples, time_unit=time_unit,
        percent_idle=percent_idle)
    df_extend_months = length_to_individual_months(
        df, idle_df, num_samples=num_samples, percent_idle=percent_idle)
    df_rate_added = add_rate_samples(df_extend_months)
    df_rate_added['Row_Script'] = df_rate_added.apply(
        generate_row_script, axis=1, MAXrate=6*(10**5), time_unit=time_unit,
        synthetic=True)
    return df_rate_added
